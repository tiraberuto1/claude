export const name='samurai';
function P(c,pts,f,s,lw){c.beginPath();pts.forEach((p,i)=>i?c.lineTo(p[0],p[1]):c.moveTo(p[0],p[1]));c.closePath();if(f){c.fillStyle=f;c.fill();}if(s){c.strokeStyle=s;c.lineWidth=lw||1.5;c.stroke();}}
function L(c,a,b,col,w,cap){c.beginPath();c.moveTo(a[0],a[1]);c.lineTo(b[0],b[1]);c.strokeStyle=col;c.lineWidth=w;c.lineCap=cap||'round';c.stroke();}
function E(c,x,y,rx,ry,f,rot){c.beginPath();c.ellipse(x,y,rx,ry,rot||0,0,7);c.fillStyle=f;c.fill();}
// 縞の鎧: 四角形 a,b(上辺) d,c(下辺) を n 段に分け色を交互に塗る
function bands(c,q,cols,n,edge){for(let i=0;i<n;i++){const t0=i/n,t1=(i+1)/n;const m=(p,r,t)=>[p[0]+(r[0]-p[0])*t,p[1]+(r[1]-p[1])*t];
 P(c,[m(q[0],q[3],t0),m(q[1],q[2],t0),m(q[1],q[2],t1),m(q[0],q[3],t1)],cols[i%cols.length]);}
 if(edge)P(c,q,null,edge,2);}
function head(c,x,y,r,face){E(c,x,y,r,r*1.1,face||'#e8c8a0');E(c,x-r*.15,y-r*.55,r*1.05,r*.65,'#1a1512');}
